const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const version=process.argv[2];
if(!/^\d+\.\d+\.\d+$/.test(version||''))throw Error('Usage: node scripts/bump-version.cjs 1.0.1');
const buildFile=path.join(root,'app/build.gradle');
let build=fs.readFileSync(buildFile,'utf8');
const old=build.match(/versionName '([^']+)'/)[1];
const code=Number(build.match(/versionCode (\d+)/)[1])+1;
const compare=(a,b)=>{const x=a.split('.').map(Number),y=b.split('.').map(Number);return x[0]-y[0]||x[1]-y[1]||x[2]-y[2];};
if(compare(version,old)<=0)throw Error(`Version must be greater than ${old}`);
build=build.replace(/versionName '[^']+'/,`versionName '${version}'`).replace(/versionCode \d+/,`versionCode ${code}`);
fs.writeFileSync(buildFile,build);
const appFile=path.join(root,'app/src/main/assets/app.js');
fs.writeFileSync(appFile,fs.readFileSync(appFile,'utf8').replace(`KargoPilot ${old}`,`KargoPilot ${version}`));
const pkgFile=path.join(root,'package.json');
const pkg=JSON.parse(fs.readFileSync(pkgFile,'utf8'));pkg.version=version;fs.writeFileSync(pkgFile,JSON.stringify(pkg,null,2)+'\n');
const lockFile=path.join(root,'package-lock.json');
const lock=JSON.parse(fs.readFileSync(lockFile,'utf8'));lock.version=version;lock.packages[''].version=version;fs.writeFileSync(lockFile,JSON.stringify(lock,null,2)+'\n');
console.log(`Updated ${old} -> ${version}; Android versionCode ${code}. Update CHANGELOG.md and RELEASE_NOTES.md before tagging.`);
